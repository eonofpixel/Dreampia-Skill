import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { resolve, join } from 'node:path'
test('student submits; authenticated admin reads, exports, deletes and audits',async({page,request,baseURL},info)=>{
 const origin=baseURL!
 for(const path of ['/api/admin/submissions','/admin/export','/api/admin/audit']) expect((await request.get(path)).status()).toBe(401)
 const identity=info.project.name==='mobile'?11:info.project.name==='tablet'?12:13
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'나의 성장 역량 진단'})).toBeVisible()
 await page.getByLabel('진단 코드').fill('invalid-code')
 await page.getByLabel('진단 코드').focus();await page.keyboard.press('Tab')
 await expect(page.getByLabel('학년',{exact:true})).toBeFocused()
 await page.getByLabel('학년',{exact:true}).fill('1')
 await page.getByLabel('반',{exact:true}).fill('2')
 await page.getByLabel('번호',{exact:true}).fill(String(identity))
 await page.getByRole('button',{name:'진단 시작'}).click()
 await expect(page.locator('p[role="alert"]')).toContainText('올바르지 않거나 만료')
 await page.getByLabel('진단 코드').fill(process.env.UI_TEST_CODE!)
 await page.getByRole('button',{name:'진단 시작'}).click()
 const groups=page.getByRole('group')
 await expect(groups).toHaveCount(4)
 await groups.nth(0).getByRole('radio').nth(0).focus();await page.keyboard.press('ArrowRight')
 await expect(groups.nth(0).getByRole('radio').nth(1)).toBeChecked()
 // Required HTML controls prevent incomplete submission.
 await page.getByRole('button',{name:'결과 확인'}).click()
 await expect(page.getByRole('heading',{name:'나의 진단 결과'})).toHaveCount(0)
 for(let index=0;index<4;index++) await groups.nth(index).getByRole('radio').nth(index===1?0:4).check()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
 const evidence=resolve(process.env.DREAMPIA_UI_EVIDENCE ?? 'ui-evidence');await mkdir(evidence,{recursive:true})
 await page.screenshot({path:join(evidence,`${info.project.name}-questions.png`),fullPage:true})
 await page.getByRole('button',{name:'결과 확인'}).click()
 await expect(page.getByRole('heading',{name:'나의 진단 결과'})).toBeVisible()
 await expect(page.getByTestId('total-score')).toHaveText('100 / 100')
 await page.screenshot({path:join(evidence,`${info.project.name}-result.png`),fullPage:true})
 const payload={code:process.env.UI_TEST_CODE,grade:1,classNumber:2,studentNumber:identity,answers:{Q001:5,Q002:1,Q003:5,Q004:5}}
 expect((await request.post('/api/submit',{headers:{Origin:origin},data:payload})).status()).toBe(409)
 expect((await request.post('/api/submit',{headers:{Origin:origin},data:{...payload,studentNumber:identity+20,answers:{Q001:9}}})).status()).toBe(400)
 expect((await request.post('/api/admin/login',{headers:{Origin:origin},data:{secret:'wrong'}})).status()).toBe(401)
 await page.goto('/admin')
 await expect(page.getByRole('heading',{name:'관리자 인증'})).toBeVisible()
 await page.getByLabel('관리자 비밀키').fill(process.env.UI_TEST_ADMIN!)
 await page.getByRole('button',{name:'로그인',exact:true}).click()
 await expect(page.getByRole('heading',{name:'진단 운영 현황'})).toBeVisible()
 const row=page.getByRole('row').filter({hasText:`1학년 2반 ${identity}번`})
 await expect(row).toBeVisible()
 await expect(row).toContainText('100')
 await expect(page.getByTestId('submission-count')).toHaveText('1건')
 await expect(page.locator('.stats')).toContainText('100점')
 await expect(page.locator('.stats')).toContainText('1학년 2반 · 1건')
 await page.reload();await expect(row).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
 await page.screenshot({path:join(evidence,`${info.project.name}-admin.png`),fullPage:true})
 const downloadPromise=page.waitForEvent('download')
 await page.getByRole('link',{name:'CSV 내려받기'}).click()
 const download=await downloadPromise
 expect(download.suggestedFilename()).toBe('assessment-submissions.csv')
 const contextRequest=page.context().request
 const csv=await contextRequest.get('/admin/export')
 expect(csv.status()).toBe(200)
 expect(await csv.text()).toContain(`"1","2","${identity}"`)
 await row.getByRole('button',{name:'삭제'}).click()
 await expect(row).toHaveCount(0)
 await page.getByRole('button',{name:'보존 기간 적용'}).click()
 await expect(page.getByRole('status')).toContainText('삭제')
 const audit=await contextRequest.get('/api/admin/audit')
 expect((await audit.json()).audit.map((x:{action:string})=>x.action)).toEqual(expect.arrayContaining(['submit','login','read','export','delete','retention']))
 expect((await contextRequest.post('/api/admin/retention',{data:{days:30},headers:{Origin:'http://evil.invalid'}})).status()).toBe(403)
 await page.getByRole('button',{name:'로그아웃'}).click()
 await expect(page.getByRole('heading',{name:'관리자 인증'})).toBeVisible()
 expect((await contextRequest.get('/admin/export')).status()).toBe(401)
})
